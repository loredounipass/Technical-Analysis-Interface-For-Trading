-- ─── Auth: User accounts ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT UNIQUE NOT NULL,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx
    ON users (lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_idx
    ON users (lower(username));

-- ─── Chat ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS chat_preferences (
    owner_id UUID PRIMARY KEY,
    selected_model TEXT NOT NULL DEFAULT 'nvidia-nemotron',
    web_search_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    legacy_imported BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS market_data_preferences (
    owner_id UUID PRIMARY KEY,
    crypto_provider TEXT NOT NULL DEFAULT 'coinbase'
        CHECK (crypto_provider IN ('binance', 'coinbase')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS chat_sessions (
    id UUID PRIMARY KEY,
    owner_id UUID NOT NULL,
    title TEXT NOT NULL,
    symbol TEXT NOT NULL DEFAULT 'BTCUSDT',
    market TEXT NOT NULL DEFAULT 'crypto',
    interval TEXT NOT NULL DEFAULT '15m',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES chat_sessions(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    timestamp BIGINT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS chat_sessions_owner_updated_idx
    ON chat_sessions (owner_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS chat_messages_session_timestamp_idx
    ON chat_messages (session_id, timestamp, id);
